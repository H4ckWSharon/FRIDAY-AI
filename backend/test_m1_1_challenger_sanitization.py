async def _collect_stream_chunks(chunks_to_yield: list[str]) -> list[str]:
    """Helper to run _stream_generator with mocked chat_stream and collect SSE text chunks."""
    async def mock_stream(messages, model):
        for c in chunks_to_yield:
            yield c

    emitted_texts = []
    with patch("routes.chat.chat_stream", side_effect=mock_stream):
        async for sse_event in _stream_generator(
            messages=[{"role": "user", "content": "test"}],
            model="orcasaq-cyber-27b:latest",
            conversation_id=None,
            user_content="test",
            user_id="challenger_uid_001",
        ):
            # Parse event: chunk \n data: {"text": "..."}
            if sse_event.startswith("event: chunk"):
                match = re.search(r'data:\s*(\{"text":\s*".*?"\})', sse_event)
                if match:
                    payload = json.loads(match.group(1))
                    emitted_texts.append(payload["text"])
    return emitted_texts


